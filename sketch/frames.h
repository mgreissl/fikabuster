const int FONT_COUNT = sizeof(FONT) / sizeof(FONT[0]);

const uint8_t *glyph(char c) {
  c = toupper(c);
  for (int i = 0; i < FONT_COUNT; i++)
    if (FONT[i].c == c) return FONT[i].rows;
  return FONT[0].rows;
}

